function getTranslation(key) {
    const lang = localStorage.getItem('app_lang') || 'en';
    if (!translations[lang]) return translations['en'][key] || key;
    return translations[lang][key] || key;
}

function updatePageTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = getTranslation(key);
    });
    
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = getTranslation(key);
    });

    // Sync language selector value
    const langSelectors = document.querySelectorAll('select[onchange="setLanguage(this.value)"]');
    const currentLang = localStorage.getItem('app_lang') || 'en';
    langSelectors.forEach(sel => {
        sel.value = currentLang;
    });
}

function setLanguage(lang) {
    localStorage.setItem('app_lang', lang);
    updatePageTranslations();
    if (typeof loadShipments === 'function') loadShipments();
    if (typeof loadMissions === 'function') loadMissions();
    if (window.logistixVoice) {
        window.logistixVoice.updateLanguage();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    updatePageTranslations();
});

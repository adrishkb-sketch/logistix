async function loadLanguage(lang) {
    if (translations[lang]) return;
    
    // Core languages (en, hi, bn) are already bundled in this file
    if (['en', 'hi', 'bn'].includes(lang)) return;

    // Determine path based on page location
    let path = `js/${lang}.json`;
    if (window.location.pathname.includes('/pages/')) {
        path = `../js/${lang}.json`;
    }
    
    try {
        const response = await fetch(path);
        if (response.ok) {
            translations[lang] = await response.json();
            console.log(`Loaded language: ${lang}`);
        } else {
            console.warn(`Translation file not found for: ${lang}`);
        }
    } catch (e) {
        console.error(`Failed to load translation: ${lang}`, e);
    }
}

function getTranslation(key) {
    const lang = localStorage.getItem('app_lang') || 'en';
    const translated = translations[lang] ? translations[lang][key] : null;
    return translated || translations['en'][key] || key;
}

function updatePageTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerHTML = getTranslation(key);
    });
    
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = getTranslation(key);
    });

    // Sync language selector value
    const langSelectors = document.querySelectorAll('select[onchange="setLanguage(this.value)"]');
    const currentLang = localStorage.getItem('app_lang') || 'en';
    langSelectors.forEach(sel => {
        sel.value = currentLang;
    });
}

async function setLanguage(lang) {
    localStorage.setItem('app_lang', lang);
    await loadLanguage(lang);
    updatePageTranslations();
    
    // Refresh page data if applicable
    if (typeof loadShipments === 'function') loadShipments();
    if (typeof loadMissions === 'function') loadMissions();
    
    // Sync voice engine
    if (window.logistixVoice) {
        window.logistixVoice.updateLanguage();
    }
}

document.addEventListener('DOMContentLoaded', async () => {
    const currentLang = localStorage.getItem('app_lang') || 'en';
    if (currentLang !== 'en' && currentLang !== 'hi' && currentLang !== 'bn') {
        await loadLanguage(currentLang);
    }
    updatePageTranslations();
});
